#!/usr/bin/env node
// Regenerates the rendered table in docs/security/INVARIANTS.md from
// docs/security/invariants.jsonl, which is the source of truth.
//
//   node scripts/gen-invariants.mjs          # rewrite INVARIANTS.md in place
//   node scripts/gen-invariants.mjs --check  # exit 1 if the .md is stale (CI)
//
// Everything between the BEGIN/END markers is machine-owned; edit the jsonl,
// never the table.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const JSONL = join(ROOT, "docs/security/invariants.jsonl");
const MD = join(ROOT, "docs/security/INVARIANTS.md");
const BEGIN = "<!-- BEGIN GENERATED: scripts/gen-invariants.mjs -->";
const END = "<!-- END GENERATED -->";

export const STATUSES = [
  "unimplemented",
  "llm-asserted",
  "test-covered",
  "mutation-tested",
  "proven",
  "holds",
];
export const EVIDENCE_TYPES = [
  "red_test",
  "static_trace",
  "formal_counterexample",
  "config_attestation",
  "primary_source",
];

export function loadLedger(path = JSONL) {
  return readFileSync(path, "utf8")
    .split("\n")
    .map((l, i) => ({ line: i + 1, text: l }))
    .filter((l) => l.text.trim().length > 0)
    .map((l) => {
      try {
        return { ...JSON.parse(l.text), __line: l.line };
      } catch (e) {
        throw new Error(`invariants.jsonl line ${l.line}: ${e.message}`);
      }
    });
}

const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

function evidenceCell(e) {
  if (!e.evidence || e.evidence.length === 0) return "—";
  return e.evidence
    .map((x) => `\`${esc(x.path)}\`${x.name ? ` :: \`${esc(x.name)}\`` : ""}`)
    .join("<br>");
}

export function render(entries) {
  const byPhase = new Map();
  for (const e of entries) {
    if (!byPhase.has(e.phase)) byPhase.set(e.phase, []);
    byPhase.get(e.phase).push(e);
  }
  const counts = {};
  for (const s of STATUSES) counts[s] = entries.filter((e) => e.status === s).length;

  const out = [];
  out.push(`_Generated by \`scripts/gen-invariants.mjs\` from \`docs/security/invariants.jsonl\` — ${entries.length} invariants. Do not edit this table by hand._`);
  out.push("");
  out.push("| status | count |");
  out.push("|---|---|");
  for (const s of STATUSES) out.push(`| \`${s}\` | ${counts[s]} |`);
  out.push("");
  for (const phase of [...byPhase.keys()].sort()) {
    out.push(`### Phase ${phase}`);
    out.push("");
    out.push("| ID | Invariant | Status | Spec | Prior art | Evidence |");
    out.push("|---|---|---|---|---|---|");
    for (const e of byPhase.get(phase)) {
      const spec = String(e.spec_ref ?? "").replace(/^docs\/superpowers\/specs\/[^#]*/, "design.md");
      out.push(
        `| \`${esc(e.id)}\` | **${esc(e.title)}** — ${esc(e.statement)} | \`${esc(e.status)}\` | ${esc(spec)} | ${(e.prior_art ?? []).map((p) => `\`${esc(p)}\``).join(", ") || "—"} | ${evidenceCell(e)} |`,
      );
    }
    out.push("");
  }
  return out.join("\n");
}

function main() {
  const entries = loadLedger();
  const md = readFileSync(MD, "utf8");
  const b = md.indexOf(BEGIN);
  const t = md.indexOf(END);
  if (b < 0 || t < 0) throw new Error(`INVARIANTS.md is missing the ${BEGIN} / ${END} markers`);
  const next = `${md.slice(0, b + BEGIN.length)}\n\n${render(entries)}\n${md.slice(t)}`;
  if (process.argv.includes("--check")) {
    if (next !== md) {
      console.error("INVARIANTS.md is stale — run: node scripts/gen-invariants.mjs");
      process.exit(1);
    }
    console.log(`INVARIANTS.md is up to date (${entries.length} invariants).`);
    return;
  }
  writeFileSync(MD, next);
  console.log(`INVARIANTS.md regenerated from ${entries.length} invariants.`);
}

if (process.argv[1] && process.argv[1].endsWith("gen-invariants.mjs")) main();
